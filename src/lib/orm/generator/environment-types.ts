import "server-only";
import type { FieldMetadata } from "../fields";
import type { ModuleGeneration } from "./generate";

/** TypeScript type of a field value as `context.env` returns it (datetime as ISO text). */
function valueType(field: FieldMetadata) {
  const base = field.kind === "integer" ? "number" : field.kind === "boolean" ? "boolean"
    : field.kind === "selection" ? field.choices.map(choice => JSON.stringify(choice.value)).join(" | ") || "string" : "string";
  return field.required || field.kind === "boolean" ? base : `${base} | null`;
}

/**
 * Field types of `context.env` for the module's own models (read-only phase): persistent public
 * fields only, the same set the runtime facade accepts. Companion tables of extensions are left
 * out; their fields belong to the extended model. No bodies, rules or permissions are exposed.
 */
export function environmentTypeFile(profile: ModuleGeneration): string | null {
  const models = profile.models
    // formReference names the model id (`<module>.<key>`); a companion names the extended one.
    .filter(entry => !entry.formReference || entry.formReference.model.startsWith(`${profile.id}.`))
    .map(entry => [entry.model.name, Object.entries(entry.model.metadata)
      .filter(([, field]) => !field.sensitive && !field.related && !field.compute && !(field.kind === "text" && field.writeOnly))
      .sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)] as const)
    .sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
  if (!models.length) return null;
  const body = models.map(([name, fields]) => {
    if (!/^[A-Z][A-Za-z0-9]*$/.test(name) || fields.some(([field]) => !/^[a-z][A-Za-z0-9]*$/.test(field))) throw new Error("Modelo o campo inválido al generar el entorno.");
    return `    ${name}: {\n${fields.map(([field, metadata]) => `      ${field}: ${valueType(metadata)};`).join("\n")}\n    };`;
  }).join("\n");
  return `// Generated by orm:generate / orm:sync. Edit the models, not this file.\n// Field types of context.env (read-only): persistent public fields of ${profile.id}.\nexport {};\n\ndeclare module "@/lib/orm/environment" {\n  interface ModelEnvironmentRegistry {\n${body}\n  }\n}\n`;
}
