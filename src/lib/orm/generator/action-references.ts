import "server-only";
import { defineActionReferences } from "../action-reference";
import type { ModuleGeneration } from "./generate";

/** Public names only. Bodies, labels, groups and parameters stay out of this static contract. */
export function actionReferenceFiles(profile: ModuleGeneration): Record<string, string> {
  const models = new Set<string>();
  return Object.fromEntries(profile.models.map(entry => {
    const name = entry.model.name;
    if (!/^[A-Z][A-Za-z0-9]*$/.test(name) || models.has(name)) throw new Error("Modelo duplicado o inválido al generar acciones.");
    models.add(name);
    const source = entry.actionReferences ?? { model: name, names: (entry.model.actions ?? []).map(action => action.name) };
    defineActionReferences(source.model, source.names);
    return [`${name}.actions.ts`, `// Generated by orm:generate / orm:sync. Edit the model, not this file.\nimport { defineActionReferences } from "@/lib/orm/action-reference";\n\nexport const ${name}Actions = defineActionReferences(${JSON.stringify(source.model)}, ${JSON.stringify([...source.names].sort())});\n`];
  }));
}
