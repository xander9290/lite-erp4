import "server-only";
import type { ModuleGeneration } from "./generate";
import type { FieldMetadata } from "../fields";

function inputType(field: FieldMetadata) {
  if (field.kind === "boolean") return "boolean";
  if (field.kind === "integer") return "number | null";
  if (field.kind === "selection") return `${field.choices.map(choice => JSON.stringify(choice.value)).join(" | ")} | null`;
  return field.kind === "text" ? "string" : "string | null";
}

/** Scalar proposals only; no identity, secrets, virtuals, sequences or managed companions. */
export function formReferenceFiles(profile: ModuleGeneration): Record<string, string> {
  return Object.fromEntries(profile.models.flatMap(entry => {
    if (!entry.formReference) return [];
    const { model, fields } = entry.formReference;
    const properties = Object.entries(fields).filter(([name, field]) => !["id", "revision", "createBy"].includes(name) && !field.sensitive && !field.readOnly && !field.sequence && !field.compute && !field.related)
      .map(([name, field]) => `  ${JSON.stringify(name)}: ${inputType(field)};`).join("\n");
    const name = entry.model.name;
    return [[`${name}.form.ts`, `// Generated by orm:generate / orm:sync. Edit the model, not this file.\nimport { defineModelFormReference } from "@/lib/modules/form-reference";\n\nexport const ${name}Form = defineModelFormReference<{\n${properties}\n}>(${JSON.stringify(model)});\n`]];
  }));
}
